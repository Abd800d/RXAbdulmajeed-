const normalize = (value: string) => value
  .toLocaleLowerCase()
  .normalize('NFKD')
  .replace(/[\u064B-\u065F\u0670]/g, '')
  .replace(/[إأآ]/g, 'ا')
  .replace(/ة/g, 'ه')
  .replace(/ى/g, 'ي')
  .replace(/[^\p{L}\p{N}]+/gu, ' ')
  .trim();

const sources = (name: string): SourceReference[] => [
  {
    label: `RxNav · ${name}`,
    url: `https://mor.nlm.nih.gov/RxNav/search?searchBy=String&searchTerm=${encodeURIComponent(name)}`,
    authority: 'NLM',
  },
  {
    label: `DailyMed labels · ${name}`,
    url: `https://dailymed.nlm.nih.gov/dailymed/search.cfm?query=${encodeURIComponent(name)}`,
    authority: 'FDA',
  },
];

type SeedDrug = Omit<Drug, 'id' | 'searchTerms' | 'sourceRefs' | 'createdAt' | 'updatedAt'> & {
  id?: string;
  sourceRefs?: SourceReference[];
};

const makeDrug = (input: SeedDrug): Drug => {
  const id = input.id ?? normalize(input.genericName).replace(/\s/g, '-');
  return {
    ...input,
    id,
    sourceRefs: input.sourceRefs ?? sources(input.genericName),
    searchTerms: Array.from(new Set([
      normalize(input.genericName),
      normalize(input.arabicName),
      ...input.aliases.map(normalize),
      normalize(input.pharmacologyClass),
      normalize(input.pharmacologyClassAr),
    ].filter(Boolean))),
    createdAt: stamp,
    updatedAt: stamp,
  };
};

